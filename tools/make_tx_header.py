#!/usr/bin/env python3
"""Copy the official SoniSpeech chirps into sonispeech_mode/tx_chirps.h (git-ignored).

The chirp files ship with the SoniSpeech dataset (zip 01, echo_profiles/tx_signals), so they
are not committed here. Run once per checkout:
    python3 tools/make_tx_header.py ~/Downloads/sonispeech_datasets/data/SoniSpeech_01_of_09/echo_profiles/tx_signals
"""
import sys
import wave
from array import array
from pathlib import Path

FILES = ["fmcw18000_b10000_l500_100k.wav", "fmcw29000_b10000_l500_100k.wav"]


def read(p):
    with wave.open(str(p)) as w:
        assert w.getframerate() == 100_000 and w.getsampwidth() == 2 and w.getnchannels() == 1, p
        a = array("h", w.readframes(w.getnframes()))
    assert len(a) == 500, (p, len(a))
    return a


src = Path(sys.argv[1]).expanduser()
out = Path(__file__).resolve().parent.parent / "sonispeech_mode" / "tx_chirps.h"
lines = ["// Generated by tools/make_tx_header.py from the SoniSpeech dataset. Do not commit.",
         "#pragma once", "#include <stdint.h>"]
for name, f in zip(("TX_CHIRP_18_28", "TX_CHIRP_29_39"), FILES):
    a = read(src / f)
    body = ",".join(str(v) for v in a)
    lines.append(f"static const int16_t {name}[500] = {{{body}}};")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
